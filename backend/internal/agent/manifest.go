// rbacYAML is a COPY of deploy/rbac/serviceaccount.yaml (go:embed cannot leave
// the module). A test (manifest_test.go) checks that the two copies are
// identical so they do not drift apart. In the agent manifest the SA/namespace
// of the direct connector are renamed to the agent's.
//
//go:embed rbac.yaml
var rbacYAML string

// policyYAML is a COPY of deploy/rbac/admission-policy.yaml (same test).
//
//go:embed policy.yaml
var policyYAML string

// AdmissionPolicies returns the panel's ValidatingAdmissionPolicies. In
// cluster-admin mode the one narrowing the admin group's RBAC writes is left
// out: bayplan:admins is cluster-admin there on purpose.
func AdmissionPolicies(clusterAdmin bool) string {
	var b strings.Builder
	for _, doc := range strings.Split(policyYAML, "\n---\n") {
		if clusterAdmin && strings.Contains(doc, "bayplan-limit-admin-rbac") {
			continue
		}
		b.WriteString("---\n")
		b.WriteString(strings.TrimSpace(doc))
		b.WriteString("\n")
	}
	return b.String()
}

const (
	agentNamespace = "bayplan-agent"
	agentSAName    = "bayplan-agent"
)

// ManifestParams is what varies per cluster.
type ManifestParams struct {
	ServerURL string // public URL of the server, without trailing slash
	ClusterID int64
	AgentKey  string
	Image     string
	Insecure  bool // BAYPLAN_INSECURE_SKIP_VERIFY (lab only)
	// CACert is the base64 PEM of the CA the agent trusts on top of the
	// system ones (BAYPLAN_CA_CERT): the server's self-signed CA or the one
	// pasted in Settings. Pinning it is what lets a self-signed server keep
	// verification (and RBAC self-update) on instead of skipping it.
	CACert string
	// ClusterAdmin adds the bindings to cluster-admin (see ClusterAdminBindings).
	ClusterAdmin bool
}

// ClusterAdminBindings returns the ClusterRoleBindings of the "cluster-admin"
// mode: the subject that reads (agent SA or cloud identity) and the
// bayplan:admins group bound to cluster-admin. They are ADDED to the scoped
// RBAC, not a replacement for it: the editors and readonly groups keep their
// ClusterRoles, and if the operator goes back to scoped mode, deleting these
// two bindings is enough. Other panels grant it to their agent
// unconditionally; here it is optional and stated in the UI.
func ClusterAdminBindings(subject string) string {
	return fmt.Sprintf(`---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRoleBinding
metadata:
  name: bayplan-cluster-admin
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: ClusterRole
  name: cluster-admin
subjects:
%s
---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRoleBinding
metadata:
  name: bayplan-impersonated-admin-cluster-admin
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: ClusterRole
  name: cluster-admin
subjects:
  - kind: Group
    name: "bayplan:admins"
    apiGroup: rbac.authorization.k8s.io
`, subject)
}

// RenderManifest generates the YAML applied with `kubectl apply -f`: namespace,
// ServiceAccount, the whole RBAC (read, impersonation and the three
// impersonated groups), the Secret with the agent credential and its
// Deployment.
//
// A single applicable document (`kubectl apply -f <URL>`): the operator does not
// need to understand anything
// about the RBAC to register the cluster.
func RenderManifest(p ManifestParams) string {
	rbac := agentRBAC()

	insecure := "false"
	if p.Insecure {
		insecure = "true"
	}
	var b strings.Builder
	fmt.Fprintf(&b, `# Bayplan agent for cluster %d. Generated by %s.
# Apply with: kubectl apply -f <this file>
apiVersion: v1
kind: Namespace
metadata:
  name: %s
---
`, p.ClusterID, p.ServerURL, agentNamespace)
	b.WriteString(rbac)
	if !strings.HasSuffix(rbac, "\n") {
		b.WriteString("\n")
	}
	b.WriteString(selfUpdateRBAC)
	b.WriteString(selfUpgradeRBAC)
	if p.ClusterAdmin {
		b.WriteString(ClusterAdminBindings(agentSubject()))
	}
	fmt.Fprintf(&b, `---
apiVersion: v1
kind: Secret
metadata:
  name: bayplan-agent
  namespace: %[1]s
type: Opaque
stringData:
  agentKey: %[2]q
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: bayplan-agent
  namespace: %[1]s
  labels:
    app.kubernetes.io/name: bayplan-agent
spec:
  replicas: 1
  strategy:
    type: Recreate
  selector:
    matchLabels:
      app.kubernetes.io/name: bayplan-agent
  template:
    metadata:
      labels:
        app.kubernetes.io/name: bayplan-agent
    spec:
      serviceAccountName: %[3]s
      securityContext:
        runAsNonRoot: true
        seccompProfile:
          type: RuntimeDefault
      containers:
        - name: agent
          image: %[4]s
          imagePullPolicy: IfNotPresent
          env:
            - name: BAYPLAN_SERVER_URL
              value: %[5]q
            - name: BAYPLAN_CLUSTER_ID
              value: %[6]q
            - name: BAYPLAN_INSECURE_SKIP_VERIFY
              value: %[7]q
            - name: BAYPLAN_CA_CERT
              value: %[8]q
            - name: BAYPLAN_IMAGE
              value: %[4]q
            - name: BAYPLAN_AGENT_KEY
              valueFrom:
                secretKeyRef:
                  name: bayplan-agent
                  key: agentKey
          resources:
            requests:
              cpu: 20m
              memory: 32Mi
            limits:
              memory: 128Mi
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities:
              drop: ["ALL"]
`, agentNamespace, p.AgentKey, agentSAName, p.Image, p.ServerURL, fmt.Sprint(p.ClusterID), insecure, p.CACert)
	// Last, so that on a cluster older than 1.30 (no ValidatingAdmissionPolicy)
	// kubectl apply has already created the agent when it fails on these.
	b.WriteString("# ValidatingAdmissionPolicies (Kubernetes 1.30+; on older clusters kubectl reports\n# these as unknown kinds and everything above is still applied).\n")
	b.WriteString(AdmissionPolicies(p.ClusterAdmin))
	return b.String()
}

func agentSubject() string {
	return fmt.Sprintf("  - kind: ServiceAccount\n    name: %s\n    namespace: %s", agentSAName, agentNamespace)
}

// agentRBAC is the embedded copy of serviceaccount.yaml with the agent SA
// instead of the technical one: the SA goes to its own namespace and the read
// ClusterRole/Binding are renamed so as not to clobber a direct connector that
// coexists in the same cluster.
func agentRBAC() string {
	rbac := strings.ReplaceAll(rbacYAML, "name: bayplan-technical\n  namespace: kube-system", "name: "+agentSAName+"\n  namespace: "+agentNamespace)
	rbac = strings.ReplaceAll(rbac, "    name: bayplan-technical\n    namespace: kube-system", "    name: "+agentSAName+"\n    namespace: "+agentNamespace)
	rbac = strings.ReplaceAll(rbac, "name: bayplan-technical\n", "name: bayplan-agent\n")
	if !strings.HasSuffix(rbac, "\n") {
		rbac += "\n"
	}
	return rbac
}

// selfUpdateRBAC lets the agent keep ITS OWN RBAC up to date: only the
// bayplan-* ClusterRoles and ClusterRoleBindings (by name; create does not
// accept names), with `escalate` and `bind` on them because the new rules a
// panel version brings may exceed what the SA holds today. Three limits that
// are not decorative: (1) this role (bayplan-agent-rbac) is NOT in the list, so
// the agent cannot widen what it is allowed to widen; (2) the agent validates
// what it receives against an allowlist compiled into its binary
// (cmd/agent/rbac.go: fixed groups and verbs, no wildcards, bindings only to
// bayplan-* roles and to its own subjects), so that not even a compromised
// server can grant it `*` or bind it to cluster-admin: the ceiling is set by
// the agent image, which the operator deploys; (3) with unverified TLS the
// agent does not self-update. Switching to cluster-admin mode still requires
// applying the manifest.
const selfUpdateRBAC = `---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: bayplan-agent-rbac
rules:
  - apiGroups: ["rbac.authorization.k8s.io"]
    resources: ["clusterroles", "clusterrolebindings"]
    verbs: ["create"]
  - apiGroups: ["rbac.authorization.k8s.io"]
    resources: ["clusterroles"]
    resourceNames: ["bayplan-agent", "bayplan-impersonator", "bayplan-impersonated-admin", "bayplan-impersonated-editor", "bayplan-impersonated-readonly"]
    verbs: ["get", "patch", "update", "escalate", "bind"]
  - apiGroups: ["rbac.authorization.k8s.io"]
    resources: ["clusterrolebindings"]
    resourceNames: ["bayplan-agent", "bayplan-impersonator", "bayplan-impersonated-admin", "bayplan-impersonated-editor", "bayplan-impersonated-readonly"]
    verbs: ["get", "patch", "update"]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRoleBinding
metadata:
  name: bayplan-agent-rbac
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: ClusterRole
  name: bayplan-agent-rbac
subjects:
  - kind: ServiceAccount
    name: bayplan-agent
    namespace: bayplan-agent
`

// selfUpgradeRBAC lets the agent change the image of ITS OWN Deployment (and
// nothing else: a Role in its namespace, scoped by name) when the server
// publishes a new version. The agent does it itself rather than the
// server, and it only accepts another tag of
// the same repository (cmd/agent/upgrade.go).
const selfUpgradeRBAC = `---
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: bayplan-agent-upgrade
  namespace: bayplan-agent
rules:
  - apiGroups: ["apps"]
    resources: ["deployments"]
    resourceNames: ["bayplan-agent"]
    verbs: ["get", "patch"]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: bayplan-agent-upgrade
  namespace: bayplan-agent
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: Role
  name: bayplan-agent-upgrade
subjects:
  - kind: ServiceAccount
    name: bayplan-agent
    namespace: bayplan-agent
`

// RenderRBACOnly is what the agent requests from the server to self-apply:
// only the scoped ClusterRoles and ClusterRoleBindings (no SA, Secret or
// Deployment, which belong to the operator). It deliberately does NOT include
// the self-update role nor the bindings to cluster-admin: those are only
// applied by the operator with the manifest, and the agent would reject them
// anyway.
func RenderRBACOnly() string {
	var b strings.Builder
	for _, doc := range strings.Split(agentRBAC(), "\n---\n") {
		if strings.Contains(doc, "\nkind: ServiceAccount\n") {
			continue
		}
		b.WriteString(strings.TrimSpace(doc))
		b.WriteString("\n---\n")
	}
	return b.String()
}

// RBACHash identifies a version of the RBAC (what the agent reports having
// applied). Short prefix: it is for comparison, not for security.
func RBACHash(yaml string) string {
	sum := sha256.Sum256([]byte(yaml))
	return hex.EncodeToString(sum[:8])
}
